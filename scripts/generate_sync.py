"""Generate the sync client modules from their async sources.

Each source module holds the async classes and the helpers they use. For every
source, this writes `<source>_sync.py` with each `Async*` class rewritten to its
sync twin; the helpers stay in the source and the sync module imports them.

Run with `--check` to fail when a committed sync module is out of date.
"""

from __future__ import annotations

import ast
import re
import subprocess
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1] / "src" / "blazing_agents"
SOURCES = (
    "_agents",
    "_artifacts",
    "_chat_connections",
    "_client",
    "_mcp_connections",
    "_memories",
    "_merchant",
    "_prompts",
    "_providers",
    "_sessions",
    "_skills",
    "_tasks",
    "_tenant",
    "_transport",
    "_usage",
    "_workspaces",
)
SUFFIX = "_sync"
TOKENS = {
    "aclose": "close",
    "aread": "read",
    "aiter_bytes": "iter_bytes",
    "aiter_text": "iter_text",
    "__aenter__": "__enter__",
    "__aexit__": "__exit__",
    "__aiter__": "__iter__",
    "__anext__": "__next__",
    "StopAsyncIteration": "StopIteration",
}
_TOKEN = re.compile(r"\b(" + "|".join(map(re.escape, TOKENS)) + r")\b")
_ASYNC_NAME = re.compile(r"\b(_?)Async(?=[A-Z])")
_LEFTOVER = re.compile(r"\b(async|await|Async\w*|asynchronous)\b")


def unasync(text: str) -> str:
    text = re.sub(r"\basync (?=def |with |for )", "", text)
    text = re.sub(r"\bawait ", "", text)
    text = _TOKEN.sub(lambda match: TOKENS[match.group(1)], text)
    return _ASYNC_NAME.sub(r"\1", text)


def _bound_names(node: ast.stmt) -> set[str]:
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return {node.name}
    return {
        target.id
        for child in ast.walk(node)
        if isinstance(child, (ast.Assign, ast.AnnAssign))
        for target in (
            child.targets if isinstance(child, ast.Assign) else [child.target]
        )
        if isinstance(target, ast.Name)
    } | {
        alias.asname or alias.name
        for child in ast.walk(node)
        if isinstance(child, (ast.Import, ast.ImportFrom))
        for alias in child.names
    }


def _import(node: ast.ImportFrom) -> str:
    """Rewrite one import, sending renamed names of sources to their sync twin."""
    module = "." * node.level + (node.module or "")
    groups: dict[str, list[str]] = {}
    for alias in node.names:
        name = unasync(alias.name)
        target = module
        if name != alias.name and node.level == 1 and node.module in SOURCES:
            target = f"{module}{SUFFIX}"
        groups.setdefault(target, []).append(
            name if alias.asname is None else f"{name} as {alias.asname}"
        )
    return "".join(
        f"from {target} import {', '.join(names)}\n" for target, names in groups.items()
    )


def _ruff(arguments: list[str], text: str, path: Path) -> str:
    return subprocess.run(
        [sys.executable, "-m", "ruff", *arguments, "--stdin-filename", str(path)],
        input=text,
        capture_output=True,
        check=True,
        text=True,
        cwd=PACKAGE.parents[1],
    ).stdout


def generate(source: str) -> str:
    path = PACKAGE / f"{source}.py"
    text = path.read_text()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    imports: list[str] = []
    helpers: set[str] = set()
    classes: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom):
            imports.append(_import(node))
        elif isinstance(node, ast.Import) or (
            isinstance(node, ast.If) and ast.unparse(node.test) == "TYPE_CHECKING"
        ):
            imports.append(f"{ast.get_source_segment(text, node)}\n")
        elif isinstance(node, ast.ClassDef) and _ASYNC_NAME.match(node.name):
            start = min([node.lineno, *(d.lineno for d in node.decorator_list)])
            classes.append(unasync("".join(lines[start - 1 : node.end_lineno])))
        else:
            helpers |= _bound_names(node)
    if not classes:
        raise SystemExit(f"{path.name} has no Async classes to generate from")
    helper_import = (
        f"from .{source} import {', '.join(sorted(helpers))}\n" if helpers else ""
    )
    body = "".join(imports) + helper_import + "\n\n" + "\n\n".join(classes)
    if leftover := sorted({match.group(0) for match in _LEFTOVER.finditer(body)}):
        raise SystemExit(f"{path.name}: async words survive unasync: {leftover}")
    target = PACKAGE / f"{source}{SUFFIX}.py"
    body = _ruff(
        ["check", "--fix-only", "--unsafe-fixes", "--select", "F401,I001,UP028", "-"],
        body,
        target,
    )
    body = _ruff(["format", "-"], body, target)
    header = f"# Generated by scripts/generate_sync.py from {path.name}; do not edit.\n"
    return header + body


def main() -> None:
    check = sys.argv[1:] == ["--check"]
    stale: list[str] = []
    for source in SOURCES:
        target = PACKAGE / f"{source}{SUFFIX}.py"
        generated = generate(source)
        if check:
            if not target.exists() or target.read_text() != generated:
                stale.append(target.name)
        else:
            target.write_text(generated)
    if stale:
        print(
            "Stale generated sync modules (run scripts/generate_sync.py): "
            + ", ".join(stale),
            file=sys.stderr,
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
